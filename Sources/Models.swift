import AppKit
import CryptoKit

enum ClipKind: String, Codable, CaseIterable {
    case text, link, image, files
    var label: String {
        switch self { case .text: return "Texte"; case .link: return "Lien"; case .image: return "Image"; case .files: return "Fichiers" }
    }
    var symbol: String {
        switch self { case .text: return "text.alignleft"; case .link: return "link"; case .image: return "photo"; case .files: return "folder" }
    }
}

struct PastePart: Codable, Equatable {
    let representations: [String: Data]
}

struct Capture {
    let kind: ClipKind
    let text: String
    let title: String
    let parts: [PastePart]
    let sourceName: String
    let sourceBundle: String
    var encoded: Data { get throws { try JSONEncoder().encode(parts) } }

    init(kind: ClipKind, text: String, title: String, parts: [PastePart], sourceName: String, sourceBundle: String) {
        self.kind = kind; self.text = text; self.title = title; self.parts = parts
        self.sourceName = sourceName; self.sourceBundle = sourceBundle
    }

    // Computed on the storage queue, never while handling a clipboard/UI event.
    var fingerprint: String {
        var hash = SHA256()
        hash.update(data: Data(kind.rawValue.utf8))
        // Text identity ignores alternate RTF/HTML encodings; whitespace is preserved.
        if kind == .text || kind == .link || kind == .files {
            hash.update(data: Data(text.utf8))
        } else {
            for part in parts {
                for key in part.representations.keys.sorted() {
                    hash.update(data: Data(key.utf8)); hash.update(data: part.representations[key]!)
                }
            }
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

struct LibrarySnapshot {
    let records: [ClipRecord]
    let counts: [LibraryFilter: Int]
}

struct ClipRecord: Identifiable, Equatable {
    let id: String
    let kind: ClipKind
    let title: String
    let preview: String
    let sourceName: String
    let sourceBundle: String
    let created: Date
    let lastCopied: Date
    let copyCount: Int
    let favorite: Bool
    let byteCount: Int
}

enum LibraryFilter: String, CaseIterable, Identifiable {
    case all, favorites, text, link, image, files
    var id: String { rawValue }
    var title: String {
        switch self {
        case .all: return "Tout l’historique"; case .favorites: return "Favoris"
        case .text: return "Textes"; case .link: return "Liens"; case .image: return "Images"; case .files: return "Fichiers"
        }
    }
    var symbol: String {
        switch self { case .all: return "square.stack.3d.up"; case .favorites: return "star"; default: return ClipKind(rawValue: rawValue)!.symbol }
    }
}

enum RecolleError: LocalizedError {
    case database(String), capacity, invalidPayload
    var errorDescription: String? {
        switch self {
        case .database(let message): return "L’historique n’a pas pu être enregistré. \(message)"
        case .capacity: return "L’espace est occupé par vos favoris. Supprimez-en quelques-uns pour reprendre l’enregistrement."
        case .invalidPayload: return "Cet élément n’est plus lisible dans l’historique."
        }
    }
}

enum CaptureReader {
    static let maxBytes = 12 * 1_024 * 1_024
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.RestoredType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type"
    ]
    static let privateApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.dashlane.Dashlane", "org.keepassxc.keepassxc",
        "com.enpass.Enpass", "com.apple.Passwords"
    ]
    static let supported: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue, NSPasteboard.PasteboardType.rtf.rawValue,
        NSPasteboard.PasteboardType.html.rawValue, NSPasteboard.PasteboardType.png.rawValue,
        NSPasteboard.PasteboardType.tiff.rawValue, NSPasteboard.PasteboardType.fileURL.rawValue,
        NSPasteboard.PasteboardType.URL.rawValue, "public.jpeg"
    ]

    static func read(_ board: NSPasteboard, sourceName: String, sourceBundle: String) throws -> Capture? {
        let items = board.pasteboardItems ?? []
        let types = Set(items.flatMap { $0.types.map(\.rawValue) })
        let ignored = ignoredTypes.map { NSPasteboard.PasteboardType($0) }
        // AppKit maps legacy type names to dynamic UTIs; availableType resolves both.
        guard !types.isDisjoint(with: supported), types.isDisjoint(with: ignoredTypes),
              board.availableType(from: ignored) == nil,
              !items.contains(where: { $0.availableType(from: ignored) != nil }),
              !privateApps.contains(sourceBundle) else { return nil }
        var size = 0
        var parts: [PastePart] = []
        for item in items {
            var representations: [String: Data] = [:]
            for type in item.types where supported.contains(type.rawValue) {
                // PNG already carries the image; avoid archiving a second, often huge TIFF.
                if item.types.contains(.png), type == .tiff || type.rawValue == "public.jpeg" { continue }
                if let data = item.data(forType: type) {
                    size += data.count
                    guard size <= maxBytes else { throw RecolleError.database("Copie trop volumineuse : limite de 12 Mo par élément.") }
                    representations[type.rawValue] = data
                }
            }
            if !representations.isEmpty { parts.append(PastePart(representations: representations)) }
        }
        guard !parts.isEmpty else { return nil }
        let files = items.compactMap { $0.string(forType: .fileURL) }.compactMap(URL.init(string:))
        if !files.isEmpty {
            let names = files.map(\.lastPathComponent)
            return Capture(kind: .files, text: files.map(\.absoluteString).joined(separator: "\n"), title: names.joined(separator: ", "), parts: parts, sourceName: sourceName, sourceBundle: sourceBundle)
        }
        // Image-first avoids keeping just the fallback text supplied by image editors.
        if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) || types.contains("public.jpeg") {
            return Capture(kind: .image, text: "Image copiée", title: "Image copiée", parts: parts, sourceName: sourceName, sourceBundle: sourceBundle)
        }
        let strings = items.compactMap { $0.string(forType: .string) ?? $0.string(forType: .URL) }
        var text = strings.joined(separator: "\n")
        if text.isEmpty, let rtf = board.data(forType: .rtf), let attributed = NSAttributedString(rtf: rtf, documentAttributes: nil) {
            text = attributed.string
        }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let url = URL(string: trimmed)
        let isLink = !trimmed.contains(where: \.isWhitespace) && ["https", "http"].contains(url?.scheme?.lowercased() ?? "") && url?.host != nil
        let title = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
        return Capture(kind: isLink ? .link : .text, text: text, title: String(title.prefix(180)), parts: parts, sourceName: sourceName, sourceBundle: sourceBundle)
    }

    static func write(_ parts: [PastePart], text: String, plain: Bool, to board: NSPasteboard) -> Bool {
        let objects: [NSPasteboardItem]
        if plain {
            let item = NSPasteboardItem(); item.setString(text, forType: .string); objects = [item]
        } else {
            objects = parts.map { part in
                let item = NSPasteboardItem()
                for (type, data) in part.representations { item.setData(data, forType: .init(type)) }
                return item
            }
        }
        guard !objects.isEmpty else { return false }
        board.clearContents()
        return board.writeObjects(objects)
    }
}

